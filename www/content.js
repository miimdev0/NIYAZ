  function azanLines(tab, shia, isFajr) {
    var L = [];
    function add(k, x, tag) { L.push({ ar: AZ[k][0], fa: AZ[k][1], x: x, tag: tag || "" }); }
    if (tab === "adhan") {
      add("akbar", 4);
      add("tawhid", 2); add("salawat", 1); add("risala", 2);
      if (shia) { add("wilaya", 2, "شهادت ثالثه · رایج در شیعه"); add("salawat", 1); }
      add("salah", 2); add("falah", 2);
      if (shia) add("khayr", 2); else if (isFajr) add("nawm", 2, "فقط در اذان صبح");
      add("akbar", 2); add("la", shia ? 2 : 1);
    } else if (shia) {
      add("akbar", 2);
      add("tawhid", 2); add("salawat", 1); add("risala", 2); add("wilaya", 2, "شهادت ثالثه");
      add("salawat", 1);
      add("salah", 2); add("falah", 2); add("khayr", 2);
      add("qad", 2);
      add("akbar", 2); add("la", 1);
    } else {
      add("akbar", 4); add("tawhid", 2); add("risala", 2); add("salah", 2); add("falah", 2);
      if (isFajr) add("nawm", 2, "فقط در اقامهٔ صبح");
      add("qad", 2); add("akbar", 2); add("la", 1);
    }
    return L;
  }

